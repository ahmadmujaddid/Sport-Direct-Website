CREATE DATABASE IF NOT EXISTS sexy_sonnet_sport CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sexy_sonnet_sport;
SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS order_items, orders, cart, payment_methods, addresses, product_sizes, products, brands, password_resets, messages, newsletter, users;
SET FOREIGN_KEY_CHECKS=1;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  phone VARCHAR(30) DEFAULT NULL,
  password VARCHAR(255) NOT NULL,
  role ENUM('customer','admin') NOT NULL DEFAULT 'customer',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE password_resets (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  token_hash CHAR(64) NOT NULL,
  expires_at DATETIME NOT NULL,
  used TINYINT(1) NOT NULL DEFAULT 0,
  INDEX (token_hash),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE brands (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE
);
-- gender: men | women | kids | baby | unisex (unisex shows under Men AND Women)
-- category: shoes | tops | bottoms | kit | gear | equipment | supplements
-- image: leave blank for auto placeholder, or paste a full URL, or a filename inside assets/img/products/
-- sale_price: NULL = not on sale
CREATE TABLE products (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  brand_id INT NOT NULL,
  category VARCHAR(30) NOT NULL DEFAULT 'shoes',
  gender VARCHAR(10) NOT NULL DEFAULT 'unisex',
  size_type VARCHAR(20) NOT NULL DEFAULT 'apparel',
  price DECIMAL(10,2) NOT NULL,
  sale_price DECIMAL(10,2) DEFAULT NULL,
  image VARCHAR(500) NOT NULL DEFAULT '',
  description TEXT,
  status ENUM('active','new','trending') NOT NULL DEFAULT 'active',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX (category), INDEX (gender),
  FOREIGN KEY (brand_id) REFERENCES brands(id)
);
CREATE TABLE product_sizes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT NOT NULL,
  size VARCHAR(30) NOT NULL,
  stock INT NOT NULL DEFAULT 0,
  UNIQUE KEY uq_prod_size (product_id, size),
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);
CREATE TABLE cart (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  product_id INT NOT NULL,
  size VARCHAR(30) NOT NULL,
  quantity INT NOT NULL DEFAULT 1,
  UNIQUE KEY uq_cart (user_id, product_id, size),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);
CREATE TABLE addresses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  recipient VARCHAR(100) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  line1 VARCHAR(200) NOT NULL,
  line2 VARCHAR(200) DEFAULT NULL,
  city VARCHAR(80) NOT NULL,
  postcode VARCHAR(12) NOT NULL,
  state VARCHAR(60) NOT NULL,
  country VARCHAR(60) NOT NULL DEFAULT 'Malaysia',
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
-- We ONLY store brand + last 4 digits. Never the full number, never the CVV.
CREATE TABLE payment_methods (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  brand VARCHAR(20) NOT NULL,
  holder VARCHAR(100) NOT NULL,
  last4 CHAR(4) NOT NULL,
  exp_month TINYINT NOT NULL,
  exp_year SMALLINT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE orders (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  subtotal DECIMAL(10,2) NOT NULL,
  shipping DECIMAL(10,2) NOT NULL DEFAULT 0,
  total DECIMAL(10,2) NOT NULL,
  payment_method VARCHAR(30) NOT NULL,
  card_last4 CHAR(4) DEFAULT NULL,
  ship_name VARCHAR(100) NOT NULL,
  ship_phone VARCHAR(30) NOT NULL,
  ship_address TEXT NOT NULL,
  status ENUM('pending','paid','shipped','delivered','cancelled') NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE order_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  product_id INT NOT NULL,
  name VARCHAR(160) NOT NULL,
  brand VARCHAR(60) NOT NULL,
  size VARCHAR(30) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  quantity INT NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
);
CREATE TABLE messages (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL,
  subject VARCHAR(150) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE newsletter (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(150) NOT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

